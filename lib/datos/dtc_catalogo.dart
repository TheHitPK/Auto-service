/// Descripción del código, o la del subsistema al que pertenece si no está en la tabla.
String descripcionDtc(String codigo) {
  final exacta = _dtc[codigo];
  if (exacta != null) return exacta;
  if (codigo.length != 5) return 'Código desconocido';
  final especifico = codigo[1] == '1' || (codigo[0] == 'P' && codigo[1] == '3');
  final sufijo = especifico ? ' (código específico del fabricante)' : '';
  return switch (codigo[0]) {
    'P' => switch (codigo[2]) {
        '0' || '1' || '2' => 'Medición de combustible y aire',
        '3' => 'Sistema de encendido / fallo de encendido',
        '4' => 'Control auxiliar de emisiones',
        '5' => 'Control de velocidad y ralentí',
        '6' => 'Computadora y circuitos de salida',
        '7' || '8' || '9' => 'Transmisión',
        _ => 'Tren motriz',
      },
    'C' => 'Chasis (frenos, dirección, suspensión)',
    'B' => 'Carrocería (airbag, A/C, confort)',
    'U' => 'Red de comunicación entre módulos',
    _ => 'Código desconocido',
  } + sufijo;
}
